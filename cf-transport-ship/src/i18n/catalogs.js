export function withPlatformBranding(catalogs = CATALOGS, override = PLATFORM_BRAND_OVERRIDE) {
  const out = {};
  for (const loc of Object.keys(catalogs)) {
    const patch = override[loc];
    out[loc] = patch ? { ...catalogs[loc], ...patch } : { ...catalogs[loc] };
  }
  return out;
}
